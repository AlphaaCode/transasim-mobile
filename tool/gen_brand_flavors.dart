/// Rewrites the per-brand asset entries in `pubspec.yaml`, between its
/// `BEGIN brand flavors` / `END brand flavors` markers, for every folder under
/// `brands/` holding a brand.json, and nothing else:
///
/// - its prod bundle, `brands/<slug>/flavor/<slug>.json`, into the store flavor;
/// - its dev bundle, `<slug>Dev.json`, into the `<slug>Dev` flavor, when it has one;
/// - its assets folder into both.
///
/// ```
/// dart run tool/gen_brand_flavors.dart
/// ```
///
/// Each brand ships its files into its own flavors only. Miss one entry and
/// every client ships every other client's files, which is why they are
/// generated rather than typed, and why brand_wiring_test fails until this has
/// been run for a new brand. brand.json itself never ships: it names the DEV
/// host, and the store build must not (Slice H). Studio generates the bundles.
/// Running it again changes nothing.
library;

import 'dart:convert';
import 'dart:io';

import 'package:transasim_mobile/core/brand/app_flavor.dart' show hostOf;

const _begin = '    # BEGIN brand flavors: generated by tool/gen_brand_flavors.dart, do not edit';
const _end = '    # END brand flavors';

/// Whether [brand] builds a dev flavor (Slice H): while `mobile.devApiBaseUrl`
/// names a host other than production's. eSimple's DEV server is its
/// production until the server merge, so it has none.
bool devFlavorEnabled(Map<String, dynamic> brand) {
  final mobile = brand['mobile'] is Map ? brand['mobile'] as Map : const {};
  final dev = hostOf('${mobile['devApiBaseUrl'] ?? ''}');
  return dev.isNotEmpty && dev != hostOf('${mobile['apiBaseUrl'] ?? ''}');
}

/// [pubspec] with the block between the markers replaced by the entries of
/// [slugs], in that order; [withDev] are those with a dev flavor.
String withBrandFlavors(String pubspec, List<String> slugs, {Set<String> withDev = const {}}) {
  final start = pubspec.indexOf(_begin);
  final end = pubspec.indexOf(_end);
  if (start < 0 || end < start) {
    throw StateError('pubspec.yaml has lost its brand flavors markers:\n$_begin\n$_end');
  }
  String entry(String path, List<String> flavors) => '    - path: $path\n      flavors: [${flavors.join(', ')}]\n';
  final entries = [
    for (final slug in slugs) ...[
      entry('brands/$slug/flavor/$slug.json', [slug]),
      if (withDev.contains(slug)) entry('brands/$slug/flavor/${slug}Dev.json', ['${slug}Dev']),
      entry('brands/$slug/assets/', [slug, if (withDev.contains(slug)) '${slug}Dev']),
    ],
  ].join();
  return '${pubspec.substring(0, start)}$_begin\n$entries${pubspec.substring(end)}';
}

/// The folders under `<root>/brands/` holding a brand.json, sorted: the same
/// list Gradle builds flavors from.
List<String> brandSlugs([String root = '.']) => [
      for (final dir in Directory('$root/brands').listSync().whereType<Directory>())
        if (File('${dir.path}/brand.json').existsSync())
          dir.uri.pathSegments.where((s) => s.isNotEmpty).last,
    ]..sort();

/// The brands of [slugs] whose brand.json builds a dev flavor.
Set<String> devSlugs(String root, Iterable<String> slugs) => {
      for (final slug in slugs)
        if (devFlavorEnabled(jsonDecode(File('$root/brands/$slug/brand.json').readAsStringSync()) as Map<String, dynamic>))
          slug,
    };

void main() {
  final slugs = brandSlugs();
  final pubspec = File('pubspec.yaml');
  final before = pubspec.readAsStringSync();
  final after = withBrandFlavors(before, slugs, withDev: devSlugs('.', slugs));
  if (after == before) {
    stdout.writeln('pubspec.yaml: brand flavors up to date (${slugs.join(', ')})');
  } else {
    pubspec.writeAsStringSync(after);
    stdout.writeln('pubspec.yaml: brand flavors rewritten for ${slugs.join(', ')}');
  }
}
